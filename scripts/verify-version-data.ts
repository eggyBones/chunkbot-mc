// Verifies the INSTALLED minecraft-data / protocol codec for a fixture profile's
// Minecraft version against Mojang's own data-generator reports from the
// SHA-1-verified official server jar (not against minecraft-data itself).
//
//   node scripts/verify-version-data.ts --fixture 26.2        (after `npm run fixture -- setup --fixture 26.2`)
//   node scripts/verify-version-data.ts                       (default 26.1.2 fixture)
//
// Steps: run `net.minecraft.data.Main --reports` from the pinned jar into
// var/compatibility/reports-<version>/ (scratch dir; never a fixture world),
// write the compact digest tests/fixtures/official-reports-<version>.json
// (checked in; used by tests/version-compat.test.ts), and compare every block
// state, registry order and packet id with the installed stack. Packet names
// are aligned through the accepted 26.1.2 reference codec; packets that are
// new in the target version need a reviewed name in REVIEWED_NEW_PACKETS, and
// label-only differences need an explicit entry in LABEL_ALIASES (scripts/lib/official-reports.ts).
// Writes var/compatibility/verify-<version>-<stamp>.json; exits 1 on any mismatch.
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { DEFAULT_FIXTURE_PROFILE, PROJECT_ROOT, fixturePaths, fixturePins, fixtureProfileFromArgv, type FixturePins } from '../src/app/fixture-layout.ts';
import { REVIEWED_NEW_PACKETS, buildDigest, compareDigest, packetCorrespondence, type ReportDigest } from './lib/official-reports.ts';

function log(line: string): void {
  process.stdout.write(`[verify-version-data] ${line}\n`);
}

function digestPath(version: string): string {
  return join(PROJECT_ROOT, 'tests', 'fixtures', `official-reports-${version}.json`);
}

function ensureDigest(pins: FixturePins): ReportDigest {
  const fx = fixturePaths(PROJECT_ROOT, pins);
  const jar = join(fx.downloads, `server-${pins.minecraftVersion}.jar`);
  if (!existsSync(jar)) throw new Error(`missing ${jar}: run npm run fixture -- setup --fixture ${pins.profile}`);
  const sha1 = createHash('sha1').update(readFileSync(jar)).digest('hex');
  if (sha1 !== pins.serverJarSha1) throw new Error(`${jar} sha1 ${sha1} != pinned ${pins.serverJarSha1}`);
  const work = join(PROJECT_ROOT, 'var', 'compatibility', `reports-${pins.minecraftVersion}`);
  const reports = join(work, 'generated', 'reports');
  if (!existsSync(join(reports, 'packets.json'))) {
    mkdirSync(work, { recursive: true });
    copyFileSync(jar, join(work, 'server.jar'));
    log(`generating official reports for ${pins.minecraftVersion} in ${work}`);
    const r = spawnSync(fx.java, ['-DbundlerMainClass=net.minecraft.data.Main', '-jar', 'server.jar', '--reports', '--output', 'generated'], { cwd: work, encoding: 'utf8' });
    if (r.status !== 0) throw new Error(`data generator exited ${r.status}: ${r.stderr}`);
  }
  const read = (f: string) => JSON.parse(readFileSync(join(reports, f), 'utf8'));
  const digest = buildDigest(
    { blocks: read('blocks.json'), registries: read('registries.json'), packets: read('packets.json') },
    {
      minecraftVersion: pins.minecraftVersion,
      serverJarSha1: pins.serverJarSha1,
      generator: 'java -DbundlerMainClass=net.minecraft.data.Main -jar server.jar --reports (official Mojang data generator)',
      note: 'GENERATED by scripts/verify-version-data.ts. Independent evidence from the official jar; do not edit by hand.',
    },
  );
  mkdirSync(join(PROJECT_ROOT, 'tests', 'fixtures'), { recursive: true });
  writeFileSync(digestPath(pins.minecraftVersion), `${JSON.stringify(digest)}\n`);
  return digest;
}

function main(): void {
  const pins = fixturePins(fixtureProfileFromArgv(process.argv));
  const referencePins = fixturePins(DEFAULT_FIXTURE_PROFILE);
  const reference = ensureDigest(referencePins);
  const digest = pins.profile === referencePins.profile ? reference : ensureDigest(pins);
  const correspondence = packetCorrespondence(reference, referencePins.minecraftVersion);
  const findings = compareDigest(digest, pins.minecraftVersion, {
    correspondence,
    newPackets: REVIEWED_NEW_PACKETS[pins.minecraftVersion] ?? {},
  });
  for (const f of findings) log(`${f.ok ? 'OK  ' : 'FAIL'} ${f.area}: ${f.detail}`);
  const stamp = new Date().toISOString().replace(/[:.]/g, '-');
  const out = join(PROJECT_ROOT, 'var', 'compatibility', `verify-${pins.minecraftVersion}-${stamp}.json`);
  writeFileSync(out, `${JSON.stringify({ version: pins.minecraftVersion, jarSha1: pins.serverJarSha1, reference: referencePins.minecraftVersion, findings }, null, 2)}\n`);
  const failed = findings.filter((f) => !f.ok).length;
  log(`${findings.length - failed}/${findings.length} checks passed; report ${out}`);
  if (failed) process.exitCode = 1;
}

main();
